"""Generate the feature coverage table (schema ``ef-coverage1``) from the core design coverage map and the io catalogue.

Internal, synthetic, pre-release. Inputs: the core map ``docs/plans/design-coverage-map.json`` and the core ownership
manifest ``docs/plans/equity-output-ownership.json`` (both read with ``git show <ref>:<path>``, never from a dirty
working tree), and the committed io catalogue ``docs/contracts/catalogue/index.json``. Output (``docs/contracts/coverage/``):
``COVERAGE.md``, ``coverage.json`` and ``coverage.schema.json``. Nothing is computed from data and nothing is invented:
a status is derived from the cited outputs or copied from the Product Owner assertion the map cites.

Every output id a row cites resolves to exactly one of four ``contract_status`` values, and never to a blank link:

* ``frozen``: an io catalogue page exists and its core freeze text says frozen;
* ``proposed_not_frozen``: an io catalogue page whose freeze text says proposed, or an EF1 id with no page (typed pointer to
  the core proposal document, RL-01-20);
* ``core_registry``: implemented in the core registry, no io-published producer contract page (typed pointer to a core document);
* ``planned``: a planned DV1 output (typed pointer to its ownership-manifest row).

    python tools/gen_coverage_table.py --core-root PATH_TO_CORE [--core-ref origin/main]   # write the three files
    python tools/check_coverage_table.py --core-root PATH_TO_CORE                           # check R1-R4 and regeneration

The packaged catalogue data is not touched.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_contract_catalogue as cat  # noqa: E402

ROOT = cat.ROOT
OUT_DIR = ROOT / "docs" / "contracts" / "coverage"
CATALOGUE_INDEX = cat.DOCS_DIR / "index.json"
MAP_PATH = "docs/plans/design-coverage-map.json"
MANIFEST_PATH = "docs/plans/equity-output-ownership.json"
SCHEMA = "ef-coverage1"
MAP_SCHEMA = "ef-design-coverage-map1"
WORDING = cat.WORDING
CONTRACT_STATUSES = ("frozen", "proposed_not_frozen", "core_registry", "planned")
STATUSES = ("implemented", "partial", "missing", "differs", "out_of_library_scope")
ASSERTED_STATUSES = ("partial", "differs", "out_of_library_scope")
LOAD_BEARING_ROLES = ("primary", "operand")
CATALOGUE_REL = "../catalogue/"
HEADER = ("Derived from core commit {commit}; judgements are asserted by the Product Owner with records; "
          "internal, synthetic, pre-release; not a release claim.")
GENERATED = "GENERATED by tools/gen_coverage_table.py, do not edit. Regenerate from core; tools/check_coverage_table.py fails on any difference."

# Pointer targets for ids with no io catalogue page, by the release the map names for the id. The first target whose text
# contains the id is used; if none does, generation fails (an unresolved pointer is never written). Family to target
# lives here, not in the map (ruling RL-01-15 X3).
CORE_REGISTRY_TARGETS: dict[str, tuple[str, ...]] = {
    "R1": ("docs/contracts/REGISTRY.md", "docs/R1_ACCEPTANCE.md", "docs/features/SESSION_FORMULAS.md", "docs/features/V1_SCOPE.md"),
    "R2": ("docs/contracts/REGISTRY.md", "docs/api/HISTORY.md", "docs/api/RELATIVE_RETURNS.md", "docs/api/EF3_RELATIVE_STATS.md",
           "docs/api/DECLARED_BREADTH.md"),
    "R17": ("docs/R17_ACCEPTANCE.md", "docs/features/INTRADAY_FOUNDATIONS.md"),
}
EF1_PROPOSAL_TARGETS = (
    "docs/ef1/PATH_CONTRACT_PROPOSAL.json", "docs/ef1/PERIOD_PHASE_CONTRACT_PROPOSAL.json", "docs/ef1/REFERENCE_CONTRACT_PROPOSAL.json",
    "docs/ef1/OBSERVABLE_CONTRACT_PROPOSAL.json", "docs/ef1/CONTRACT.json", "docs/ef1/audit/EQ164_WAVE4_FIELD_DELIVERY.json",
    "docs/ef1/gap_endpoint/GAP_ENDPOINT_ORACLE.json",
)
BANNER_EF1 = "EF1 outputs: proposed, not frozen (RL-01-20)."
BANNER_DV1 = "DV1 outputs: manifest says delivered, catalogue pages pending."
BANNER_REGISTRY = "Core-registry outputs: implemented in the core registry; no io-published producer contract page."


def object_schema(required: list[str], properties: dict[str, Any]) -> dict[str, Any]:
    return {"type": "object", "required": required, "properties": properties}


POINTER_SCHEMA = object_schema(["kind", "core_path", "core_commit", "sha256_lf", "core_link"], {
    "kind": {"enum": ["core_registry", "core_proposal", "ownership_manifest"]}, "core_path": {"type": "string"},
    "core_commit": {"type": "string"}, "sha256_lf": {"type": "string"}, "core_link": {"type": "string"}, "row": {"type": "object"}})
CATALOGUE_LINK_SCHEMA = object_schema(["kind", "json", "md"], {"kind": {"const": "catalogue"}, "json": {"type": "string"}, "md": {"type": "string"}})
OUTPUT_SCHEMA = object_schema(
    ["feature_id", "role", "release", "contract_status", "producer_id", "input_contract", "output_contract", "delivered", "accepted"],
    {"feature_id": {"type": "string"}, "role": {"enum": ["primary", "operand", "variant", "existing_differs"]}, "release": {"type": "string"},
     "contract_status": {"enum": list(CONTRACT_STATUSES)}, "producer_id": {"type": ["string", "null"]},
     "input_contract": {"oneOf": [CATALOGUE_LINK_SCHEMA, POINTER_SCHEMA]}, "output_contract": {"oneOf": [CATALOGUE_LINK_SCHEMA, POINTER_SCHEMA]},
     "delivered": {"type": "boolean"}, "accepted": {"type": "boolean"}})
ITEM_SCHEMA = object_schema(
    ["design_id", "family", "kind", "title", "design_ref", "status", "status_basis", "provisional", "composition", "outputs", "rollup"],
    {"design_id": {"type": "string"}, "family": {"type": "string"}, "kind": {"type": "string"}, "title": {"type": "string"},
     "design_ref": {"type": "string"}, "status": {"enum": list(STATUSES)}, "status_basis": {"type": "string"}, "provisional": {"type": "boolean"},
     "composition": {"type": "string"}, "outputs": {"type": "array", "items": OUTPUT_SCHEMA}, "rollup": {"type": "string"}})
SCHEMA_DOC = {
    "$schema": "http://json-schema.org/draft-07/schema#", "title": SCHEMA, "description": GENERATED + " " + WORDING + ".",
    **object_schema(["schema", "wording", "generated_from", "counts", "items", "extras"], {
        "schema": {"const": SCHEMA}, "wording": {"const": WORDING}, "generated_from": {"type": "object"}, "counts": {"type": "object"},
        "items": {"type": "array", "items": ITEM_SCHEMA}, "extras": {"type": "array"}}),
}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class Core:
    """Reads files of a core checkout at a fixed ref (LF bytes plus last touching commit)."""

    def __init__(self, root: Path, ref: str) -> None:
        self.root, self.ref = root, ref
        self.cache: dict[str, tuple[bytes, str]] = {}

    def read(self, path: str) -> tuple[bytes, str]:
        if path not in self.cache:
            if not path or subprocess.run(["git", "-C", str(self.root), "cat-file", "-e", f"{self.ref}:{path}"], capture_output=True).returncode != 0:
                raise FileNotFoundError(f"{path} is not in core at {self.ref}")
            self.cache[path] = cat.read_core(self.root, self.ref, path)
        return self.cache[path]

    def text(self, path: str) -> str:
        return self.read(path)[0].decode("utf-8")

    def pointer(self, kind: str, path: str, row: dict[str, Any] | None = None) -> dict[str, Any]:
        raw, commit = self.read(path)
        out = {"kind": kind, "core_path": path, "core_commit": commit, "sha256_lf": sha(raw), "core_link": cat.CORE_BLOB + commit + "/" + path}
        if row is not None:
            out["row"] = row
        return out


def manifest_rows(manifest: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """canonical name to {section, planned_delivery, accepted, implemented} for every manifest output."""
    rows: dict[str, dict[str, Any]] = {}
    for row in manifest["outputs"]:
        rows[row["canonical_name"]] = {"section": "outputs", "planned_delivery": row["planned_delivery"], "accepted": bool(row.get("accepted"))}
    for key, value in manifest.items():
        if key.endswith("_delivered_outputs"):
            for row in value["entries"]:
                rows[row["canonical_name"]] = {"section": key, "planned_delivery": row["planned_delivery"], "accepted": bool(row.get("accepted"))}
    return rows


def first_target(core: Core, targets: tuple[str, ...], feature_id: str) -> str | None:
    for path in targets:
        try:
            if feature_id in core.text(path):
                return path
        except Exception:  # noqa: BLE001 - a missing target file is "does not resolve"
            continue
    return None


def resolve_output(core: Core, index: dict[str, Any], rows: dict[str, dict[str, Any]], entry: dict[str, Any], problems: list[str]) -> dict[str, Any] | None:
    """One cited output id to one of the four contract states, with a link or typed pointer, never blank."""
    fid, release = entry["id"], entry["release"]
    manifest = rows.get(fid)
    accepted = bool(manifest and manifest["accepted"])
    base = {"feature_id": fid, "role": entry["role"], "release": release, "accepted": accepted}
    pid = index["by_feature_id"].get(fid)
    if pid is not None:
        producer = next(p for p in index["producers"] if p["producer_id"] == pid)
        status = "frozen" if producer["status"] == "frozen" else "proposed_not_frozen"
        paths = producer["paths"]
        out_link = {"kind": "catalogue", "json": CATALOGUE_REL + paths["output_json"], "md": CATALOGUE_REL + paths["output_md"]}
        in_link = {"kind": "catalogue", "json": CATALOGUE_REL + paths["input_json"], "md": CATALOGUE_REL + paths["input_md"]}
        return {**base, "contract_status": status, "producer_id": pid, "input_contract": in_link, "output_contract": out_link, "delivered": True}
    if release == "DV1":
        if fid not in rows or rows[fid]["planned_delivery"] != "DV1":
            problems.append(f"R1: {fid} is cited as DV1 but has no DV1 row in the ownership manifest")
            return None
        pointer = core.pointer("ownership_manifest", MANIFEST_PATH, {"section": rows[fid]["section"], "canonical_name": fid})
        return {**base, "contract_status": "planned", "producer_id": None, "input_contract": pointer, "output_contract": pointer, "delivered": False}
    if release == "EF1":
        path = first_target(core, EF1_PROPOSAL_TARGETS, fid)
        if path is None:
            problems.append(f"R1: EF1 id {fid} is in no core EF1 proposal document (pointer does not resolve)")
            return None
        pointer = core.pointer("core_proposal", path)
        return {**base, "contract_status": "proposed_not_frozen", "producer_id": None, "input_contract": pointer, "output_contract": pointer, "delivered": False}
    if release in CORE_REGISTRY_TARGETS:
        path = first_target(core, CORE_REGISTRY_TARGETS[release], fid)
        if path is None:
            problems.append(f"R1: {release} id {fid} is in none of {list(CORE_REGISTRY_TARGETS[release])} (pointer does not resolve)")
            return None
        pointer = core.pointer("core_registry", path)
        return {**base, "contract_status": "core_registry", "producer_id": None, "input_contract": pointer, "output_contract": pointer, "delivered": True}
    problems.append(f"R1: {fid} has release {release}, no io page and no pointer rule")
    return None


def derive_status(item: dict[str, Any], outputs: list[dict[str, Any]]) -> tuple[str, str]:
    """(status, rollup). Asserted statuses are copied; missing and implemented are derived; implemented never upgrades."""
    asserted = item.get("status") in ASSERTED_STATUSES and item.get("asserted")
    if asserted:
        return item["status"], "status asserted by the Product Owner (" + item["asserted"].get("record", "") + ")"
    if not outputs:
        return "missing", "no cited output"
    undelivered = [o for o in outputs if o["role"] in LOAD_BEARING_ROLES and not o["delivered"]]
    if undelivered:
        names = ", ".join(f"{o['feature_id']} ({o['contract_status']})" for o in undelivered)
        return "partial", "cites output that is not delivered: " + names + ("; EF1 proposed, not frozen (RL-01-20)" if any(o["release"] == "EF1" for o in undelivered) else "")
    return "implemented", "all load-bearing outputs delivered"


def build(core_root: Path, ref: str, map_doc: dict[str, Any] | None = None) -> tuple[dict[str, Any], list[str]]:
    """The coverage document and the list of resolution problems (empty when every id resolves)."""
    core = Core(core_root, ref)
    raw_map, map_commit = core.read(MAP_PATH)
    raw_manifest, manifest_commit = core.read(MANIFEST_PATH)
    doc = map_doc if map_doc is not None else json.loads(raw_map.decode("utf-8"))
    manifest = json.loads(raw_manifest.decode("utf-8"))
    index = json.loads(CATALOGUE_INDEX.read_text(encoding="utf-8"))
    rows = manifest_rows(manifest)
    problems: list[str] = []
    if doc.get("schema") != MAP_SCHEMA:
        problems.append("R3: map schema is not " + MAP_SCHEMA)
    items: list[dict[str, Any]] = []
    resolved: dict[str, dict[str, Any]] = {}
    for raw in doc["items"]:
        outputs = []
        for entry in raw["outputs"]:
            if entry["id"] not in resolved:
                one = resolve_output(core, index, rows, entry, problems)
                if one is not None:
                    resolved[entry["id"]] = one
            if entry["id"] in resolved:
                outputs.append({**resolved[entry["id"]], "role": entry["role"], "release": entry["release"]})
        status, rollup = derive_status(raw, outputs)
        items.append({
            "design_id": raw["design_id"], "family": raw["family"], "kind": raw["kind"], "title": raw["title"], "design_ref": raw["design_ref"],
            "status": status, "status_basis": raw.get("status_basis", "derived"), "provisional": bool(raw.get("provisional")),
            "composition": raw.get("composition", "none"), "asserted": raw.get("asserted"), "note": raw.get("note", ""),
            "evidence": raw.get("evidence", []), "outputs": outputs, "rollup": rollup,
            "pinned_status": raw["status"],
        })
    cited = {o["feature_id"] for item in items for o in item["outputs"]}
    extra_groups = {o["id"]: e["extra_id"] for e in doc.get("extras", []) for o in e["outputs"]}
    extras = []
    for fid, pid in index["by_feature_id"].items():
        if fid not in cited:
            producer = next(p for p in index["producers"] if p["producer_id"] == pid)
            extras.append({"feature_id": fid, "producer_id": pid, "family": producer["family"], "listed_in_map_extra": extra_groups.get(fid)})
    counts = count(items, resolved, extras, doc)
    marker = doc.get("pending_catalogue")
    banners = [BANNER_REGISTRY] if counts["contract_status"]["core_registry"] else []
    if counts["contract_status"]["proposed_not_frozen_pointer"]:
        banners.append(BANNER_EF1)
    if marker:
        banners.append(BANNER_DV1)
    out = {
        "schema": SCHEMA, "generated": GENERATED, "wording": WORDING, "header": HEADER.format(commit=map_commit[:12]), "banners": banners,
        "catalogue_version": index["catalogue_version"],
        "generated_from": {"core_map": {"path": MAP_PATH, "core_commit": map_commit, "sha256_lf": sha(raw_map)},
                           "core_manifest": {"path": MANIFEST_PATH, "core_commit": manifest_commit, "sha256_lf": sha(raw_manifest)},
                           "io_catalogue_index_sha256": sha(CATALOGUE_INDEX.read_bytes()), "design_basis": doc["design_basis"]},
        "pending_catalogue_marker": marker if marker else None, "counts": counts, "items": items, "extras": extras,
    }
    return out, problems


def count(items: list[dict[str, Any]], resolved: dict[str, dict[str, Any]], extras: list[dict[str, Any]], doc: dict[str, Any]) -> dict[str, Any]:
    status = {s: 0 for s in STATUSES}
    for item in items:
        if not (item["status"] == "implemented" and item["provisional"]):
            status[item["status"]] += 1
    by_family: dict[str, dict[str, int]] = {}
    for item in items:
        fam = by_family.setdefault(item["family"], {s: 0 for s in STATUSES})
        fam[item["status"]] += 1
    contract = {s: 0 for s in CONTRACT_STATUSES}
    for one in resolved.values():
        contract[one["contract_status"]] += 1
    contract["proposed_not_frozen_pointer"] = sum(1 for o in resolved.values() if o["contract_status"] == "proposed_not_frozen" and o["producer_id"] is None)
    return {
        "items": len(items), "implemented_confirmed": status["implemented"],
        "implemented_provisional": sum(1 for i in items if i["status"] == "implemented" and i["provisional"]),
        "partial": status["partial"], "missing": status["missing"], "differs": status["differs"], "out_of_library_scope": status["out_of_library_scope"],
        "by_family": dict(sorted(by_family.items())), "cited_output_ids": len(resolved), "contract_status": contract,
        "map_extra_groups": len(doc.get("extras", [])), "catalogue_ids_not_cited_by_any_item": len(extras),
    }


def link_md(o: dict[str, Any], which: str) -> str:
    link = o[which]
    if link["kind"] == "catalogue":
        return f"[{which.split('_')[0]}]({link['md']})"
    return f"[{link['kind']}]({link['core_link']})"


def coverage_md(doc: dict[str, Any]) -> bytes:
    c = doc["counts"]
    L = [f"<!-- {GENERATED} -->", "", "# Feature coverage table", "", f"Scope: {WORDING}. {doc['header']}", ""]
    for b in doc["banners"]:
        L += [f"> {b}", ""]
    L += [f"Catalogue version {doc['catalogue_version']}. Machine-readable copy: [coverage.json](coverage.json), schema `{SCHEMA}` in [coverage.schema.json](coverage.schema.json). "
          "Back to the [contract catalogue](../catalogue/INDEX.md).", "",
          "## Counts", "", f"{c['items']} design items. Provisional rows are counted apart and never summed with confirmed rows.", "",
          "| Status | Count |", "| --- | --- |",
          f"| implemented (confirmed) | {c['implemented_confirmed']} |", f"| implemented (provisional) | {c['implemented_provisional']} |",
          f"| partial | {c['partial']} |", f"| differs | {c['differs']} |", f"| missing | {c['missing']} |",
          f"| out_of_library_scope | {c['out_of_library_scope']} |", "",
          f"Cited output ids: {c['cited_output_ids']}. By contract status: frozen {c['contract_status']['frozen']}; proposed_not_frozen {c['contract_status']['proposed_not_frozen']} "
          f"(of which pointer to a core proposal, no io page: {c['contract_status']['proposed_not_frozen_pointer']}); core_registry {c['contract_status']['core_registry']}; planned {c['contract_status']['planned']}. "
          f"Catalogue ids cited by no item: {c['catalogue_ids_not_cited_by_any_item']} (listed in coverage.json under extras).", "",
          "`contract_status` values: `frozen` (io catalogue page, frozen), `proposed_not_frozen` (page or core proposal whose freeze text says proposed), "
          "`core_registry` (implemented in the core registry; no io-published producer contract page), `planned` (DV1 output named in the ownership manifest only). "
          "Links are catalogue pages or typed pointers to a core document at a pinned commit; none is blank.", ""]
    families: dict[str, list[dict[str, Any]]] = {}
    for item in doc["items"]:
        families.setdefault(item["family"], []).append(item)
    for fam in sorted(families):
        L += [f"## {fam}", "", "| Id | Title | Status | Outputs (contract status, input, output) |", "| --- | --- | --- | --- |"]
        for item in families[fam]:
            status = item["status"] + (" (provisional)" if item["provisional"] else "")
            if item["status"] == "partial" and item["status_basis"] == "derived":
                status += ": " + item["rollup"]
            outs = "<br>".join(f"`{o['feature_id']}` {o['contract_status']} {link_md(o, 'input_contract')} {link_md(o, 'output_contract')}" for o in item["outputs"]) or "none"
            L.append(f"| {item['design_id']} | {cat.cell(item['title'])} | {cat.cell(status)} | {outs} |")
        L.append("")
    L += ["## Catalogue ids cited by no item", "", f"{len(doc['extras'])} ids; each is an extra, not an error.", ""]
    return ("\n".join(L) + "\n").encode("ascii", "replace")


def generate(core_root: Path, ref: str, map_doc: dict[str, Any] | None = None) -> dict[str, bytes]:
    doc, problems = build(core_root, ref, map_doc)
    if problems:
        raise SystemExit("coverage table: ids do not resolve:\n  " + "\n  ".join(problems))
    return {"COVERAGE.md": coverage_md(doc), "coverage.json": cat.dumps(doc), "coverage.schema.json": cat.dumps(SCHEMA_DOC)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--core-root", type=Path, required=True)
    parser.add_argument("--core-ref", default="origin/main")
    args = parser.parse_args()
    files = generate(args.core_root, args.core_ref)
    cat.write_tree(OUT_DIR, files)
    print(f"wrote {len(files)} files to {OUT_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
