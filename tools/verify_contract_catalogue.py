"""Content checks on the generated contract catalogue (stdlib only; no unit tests, by policy).

Internal, synthetic, pre-release. Checks, for both copies (docs and packaged data):
  - every file carries the GENERATED marker and the authority line (``.md`` as a comment/line, ``.json`` as fields);
  - the wording constraint 'internal, synthetic, pre-release' is present on every page;
  - no provider name appears in any page, JSON or error text (the list is below; extend it when a provider is added);
  - provenance (contract_version, status, source path/commit/sha256) is present on every producer view;
  - unparsed key lists are empty for every shipped contract;
  - every feature id of the output views resolves in ``by_feature_id`` to exactly one producer;
  - the package metadata ships the catalogue data files.

    python tools/verify_contract_catalogue.py
"""
from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_contract_catalogue as gen  # noqa: E402

PROVIDERS = ("databento", "fmp", "financial modeling prep", "polygon", "alpaca", "iex", "tiingo", "yahoo", "bloomberg", "refinitiv",
             "factset", "intrinio", "finnhub", "alpha vantage", "alphavantage", "quandl", "twelve data", "interactive brokers")
PROVIDER_RE = re.compile(r"(?<![a-z0-9])(" + "|".join(re.escape(p) for p in PROVIDERS) + r")(?![a-z0-9])", re.IGNORECASE)
errors: list[str] = []


def check_tree(label: str, directory: Path) -> None:
    files = sorted(p for p in directory.rglob("*") if p.is_file())
    if not files:
        errors.append(f"{label}: no files")
    for path in files:
        rel = path.relative_to(directory).as_posix()
        text = path.read_text(encoding="utf-8")
        where = f"{label}/{rel}"
        for m in PROVIDER_RE.finditer(text):
            errors.append(f"{where}: provider name {m.group(1)!r}")
        if gen.WORDING not in text:
            errors.append(f"{where}: missing wording {gen.WORDING!r}")
        if gen.AUTHORITY not in text:
            errors.append(f"{where}: missing authority line")
        if "GENERATED by tools/gen_contract_catalogue.py" not in text:
            errors.append(f"{where}: missing GENERATED marker")
        if rel.endswith(".json"):
            data = json.loads(text)
            if data.get("schema") != gen.SCHEMA:
                errors.append(f"{where}: schema {data.get('schema')!r}")
            if "producer_id" in data:
                s = data.get("source", {})
                for key in ("core_path", "core_commit", "sha256_lf"):
                    if not s.get(key):
                        errors.append(f"{where}: source.{key} missing")
                for key in ("contract_version", "status"):
                    if not data.get(key):
                        errors.append(f"{where}: {key} missing")
                if data.get("status") not in ("frozen", "proposed"):
                    errors.append(f"{where}: status {data.get('status')!r}")
                if data.get("unparsed_producer_keys"):
                    errors.append(f"{where}: unparsed producer keys {data['unparsed_producer_keys']}")
    index = json.loads((directory / "index.json").read_text(encoding="utf-8"))
    for c in index["contracts"]:
        if c["unparsed_top_level_keys"] or c["unparsed_producer_keys"]:
            errors.append(f"{label}: unparsed keys in {c['contract_key']}")
    seen: dict[str, str] = {}
    for p in index["producers"]:
        out = json.loads((directory / p["paths"]["output_json"]).read_text(encoding="utf-8"))
        for fid in out["feature_ids"]:
            if index["by_feature_id"].get(fid) != p["producer_id"]:
                errors.append(f"{label}: by_feature_id[{fid}] != {p['producer_id']}")
            if fid in seen:
                errors.append(f"{label}: duplicate feature id {fid}")
            seen[fid] = p["producer_id"]
    if set(seen) != set(index["by_feature_id"]):
        errors.append(f"{label}: by_feature_id has ids no output view lists")


check_tree("docs/contracts/catalogue", gen.DOCS_DIR)
check_tree("packaged catalogue", gen.PACKAGE_DIR)
pyproject = tomllib.loads((gen.ROOT / "packages/io-contracts/pyproject.toml").read_text(encoding="utf-8"))
shipped = pyproject["tool"]["setuptools"]["package-data"]["equity_feature_io_contracts"]
for pattern in ("catalogue/*.json", "catalogue/*.md", "catalogue/*/*.json", "catalogue/*/*.md"):
    if pattern not in shipped:
        errors.append(f"io-contracts package-data does not ship {pattern}")
scanned = [gen.ROOT / "docs/contracts/CATALOGUE.md", gen.ROOT / "tools/gen_contract_catalogue.py", gen.ROOT / "tools/check_contract_catalogue.py"]
for path in scanned:
    for m in PROVIDER_RE.finditer(path.read_text(encoding="utf-8")):
        errors.append(f"{path.relative_to(gen.ROOT)}: provider name {m.group(1)!r}")
if errors:
    raise SystemExit("contract catalogue content check failed:\n" + "\n".join(errors))
print("contract catalogue content OK: wording, authority and GENERATED markers, provenance, no provider names, no unparsed keys, feature ids unique, data files shipped.")
