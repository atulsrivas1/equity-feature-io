def input_md(v: dict[str, Any]) -> bytes:
    L = banner(v, "Input contract")
    L += ["## 1. Roles and slots (library order)", "", "| Slot | Role | Batch kind | Nullable |", "| --- | --- | --- | --- |"]
    for r in v["roles"]:
        L.append(f"| {r['slot']} | `{r['role']}` | {cell(r['kind']) if r['kind'] is not None else 'not stated'} | {cell(r['nullable']) if r['nullable'] is not None else 'not stated'} |")
    if not v["roles"]:
        L += ["", "The core contract states no role table for this producer; its supplied inputs are described only by the rules in section 5 and by the adapter API page in section 7."]
    L += ["", "## 2. Required columns and per-role rules", "", "Core states required columns inside the role text; it is copied unchanged.", ""]
    for r in v["roles"]:
        L.append(f"- `{r['role']}`: {r['contract'] if r['contract'] is not None else 'no role text in the core contract; see the reference fact schemas'}")
    L += ["", "## 3. Reference fact kinds and schemas", ""]
    rfs = v["reference_fact_schemas"]
    L += render_value(rfs) if rfs else ["The core contract states no reference fact schemas."]
    L += ["", "The schemas are listed for the whole core contract file, that is for all of its producers.", "", "## 4. Config parameters, defaults and who supplies them", ""]
    L += [f"- {p['text'] if p['name'] is None else '`' + p['name'] + '`: ' + (p['text'] if isinstance(p['text'], str) else json.dumps(p['text'], ensure_ascii=True))}" for p in v["config_parameters"]] or ["No parameters listed."]
    L += ["", "Parameters are listed as the core contract states them. Where core states a defaults position it is in the parameter text or under rules (`defaults_ledger`); the catalogue adds none.", ""]
    L += ["## 5. Coverage, adjustment, scale, known_at and mode rules", ""]
    rules = {k: x for k, x in v["rules"].items() if k not in ("refusal_precedence", "refusal_model", "shared_validator_split")}
    L += render_value(rules) if rules else ["No such rules are stated outside the role text."]
    L += ["", "## 6. Input-stage refusals", ""]
    ref = {k: x for k, x in v["rules"].items() if k in ("refusal_precedence", "refusal_model", "shared_validator_split")}
    L += render_value(ref) if ref else ["The core contract states no separate refusal order."]
    if v["refusal_codes"]:
        L += ["", "Refusal codes the core contract records for this producer (distinct code and raising layer; fixture ids are core ids):", "",
              "| Code | Raised by | Fixtures | Example (core text) |", "| --- | --- | --- | --- |"]
        for g in v["refusal_codes"]:
            ids = g["fixture_ids"]
            shown = ", ".join(ids[:6]) + (f" (+{len(ids) - 6} more)" if len(ids) > 6 else "")
            L.append(f"| `{g['error_code']}` | {cell(g['raised_by']) if g['raised_by'] else 'not stated'} | {shown} | {cell(g['example']) if g['example'] else ''} |")
    L += ["", "## 6b. Grain", "", "Core states: " + (cell(v["grain"]) if v["grain"] else "no grain (the word does not occur in the core contract). The scope of a result is described only by the role texts in section 2 (target entity, session or slot).")]
    a = v["adapter"]
    L += ["", "## 7. Adapter API", "", f"- reference storage module (the project's own storage package; never the data supplier): `{a['io_module']}`", f"- call API: [{a['api_page']}]({a['api_link']})", f"- source checkpoint: `{a['checkpoint']}`", ""]
    return "\n".join(L).encode("ascii") if False else ("\n".join(L)).encode("utf-8")


def output_md(v: dict[str, Any]) -> bytes:
    L = banner(v, "Output contract")
    L += [f"## 1. Feature ids ({len(v['headers'])})", "", "| Feature id | dtype | unit | scale | available when | other core fields |", "| --- | --- | --- | --- | --- | --- |"]
    for h in v["headers"]:
        L.append(f"| `{h['feature_id']}` | {h['dtype']} | {cell(h['unit'])} | {cell(h['scale']) if h['scale'] is not None else 'not stated'} | "
                 f"{cell(h['available_when']) if h['available_when'] is not None else 'not stated'} | {cell(h['other_core_fields']) if h['other_core_fields'] else ''} |")
    L += ["", f"Order: {v.get('header_order', 'not stated in the core contract')}", "", "## 2. Quality vocabulary, readiness and evidence", ""]
    L += render_value(v["quality"]) if "quality" in v else ["not stated"]
    L += ["", "## 3. Reasons reached (fixture ids in core)", ""]
    L += render_value(v["reasons_reached"]) if "reasons_reached" in v else ["The core contract states no reasons-reached table."]
    for key, title in (("refused_definition", "Refused outcomes"), ("known_limits", "Known limits"), ("unit_additions", "Unit additions used by these ids")):
        if key in v:
            L += ["", f"## {title}", ""] + render_value(v[key])
    L += ["", "## Headers as FeatureHeader values", "", "`dtype` is the `ValueType` string value. Fields are those of `equity_feature_io_contracts.FeatureHeader`.", "",
          "| feature_id | algorithm_version | dtype | unit | schema_version |", "| --- | --- | --- | --- | --- |"]
    for h in v["headers"]:
        f = h["feature_header_value"]
        L.append(f"| `{f['feature_id']}` | `{f['algorithm_version']}` | {f['dtype']} | {cell(f['unit'])} | {f['schema_version']} |")
    L.append("")
    return "\n".join(L).encode("utf-8")


def index_md(index: dict[str, Any]) -> bytes:
    L = [f"<!-- {GENERATED} -->", "", "# Contract catalogue", "", f"Scope: {WORDING}. {AUTHORITY}", "",
         f"Catalogue version {index['catalogue_version']}; families present: {', '.join(index['families_present'])}. Schema `{SCHEMA}`, described in [CATALOGUE.md](https://github.com/atulsrivas1/equity-feature-io/blob/main/docs/contracts/CATALOGUE.md).", "",
         "Each producer has an input view (what an adapter supplies) and an output view (what a consumer receives), as `.md` for reading and `.json` for programs, at `<producer_id>/input.*` and `<producer_id>/output.*`.", ""]
    for fam in index["families_present"]:
        L += [f"## {fam}", "", "| Producer | contract_version | status | Input | Output | Adapter API | Feature ids |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for p in index["producers"]:
            if p["family"] == fam:
                pid = p["producer_id"]
                L.append(f"| `{pid}` | `{p['contract_version']}` | {p['status']} | [input]({pid}/input.md) | [output]({pid}/output.md) | [{p['adapter']['api_page'].split('/')[-1]}]({p['adapter']['api_link']}) | {len(p['feature_ids'])} |")
        L.append("")
    L += ["## Core contract files not catalogued yet", "",
          "These core contract files exist but are not in the catalogue; the EF1 family is therefore partly present. Each is listed with its own core status text (core wins).", "",
          "| Core file | Core status text | Reason |", "| --- | --- | --- |"]
    L += [f"| `{d['core_path']}` | {cell(d['core_status_text'])} | {cell(d['reason'])} |" for d in index["not_catalogued_core_files"]]
    L += ["", "## Find a producer from a feature id", "", "`index.json` holds `by_feature_id`, a map from each feature id to its producer id.", ""]
    return "\n".join(L).encode("utf-8")


def attach_design_items(files: dict[str, bytes], core_root: Path, ref: str) -> None:
    """Reverse view (RL-01-15, CV1 part 3): add to each producer output page the design items that cite its feature ids.

    Only ids that have a catalogue page appear (core-registry, planned and EF1-pointer ids appear in the coverage table only).
    Items come from the core design coverage map; statuses are those of the coverage table.
    """
    import gen_coverage_table as cov  # noqa: PLC0415 - lazy: gen_coverage_table imports this module

    doc, problems = cov.build(core_root, ref)
    if problems:
        raise SystemExit("coverage table: ids do not resolve:\n  " + "\n  ".join(problems))
    by_producer: dict[str, list[dict[str, Any]]] = {}
    for item in doc["items"]:
        mine: dict[str, list[str]] = {}
        roles: dict[str, str] = {}
        for o in item["outputs"]:
            if o["producer_id"] is not None:
                mine.setdefault(o["producer_id"], []).append(o["feature_id"])
                roles.setdefault(o["producer_id"], o["role"])
        for pid, ids in mine.items():
            by_producer.setdefault(pid, []).append({
                "design_id": item["design_id"], "title": item["title"], "status": item["status"] + (" (provisional)" if item["provisional"] else ""),
                "role": roles[pid], "feature_ids": sorted(set(ids))})
    for name in sorted(k for k in files if k.endswith("/output.json")):
        pid = name.split("/")[0]
        view = json.loads(files[name].decode("utf-8"))
        items = sorted(by_producer.get(pid, []), key=lambda i: i["design_id"])
        view["design_items"] = items
        files[name] = dumps(view)
        md = files[pid + "/output.md"].decode("utf-8").rstrip("\n").split("\n")
        md += ["", "## Design items served", "",
               "Design items (from the core design coverage map) that cite a feature id of this producer. Status is the one in the "
               "[coverage table](https://github.com/atulsrivas1/equity-feature-io/blob/main/docs/contracts/coverage/COVERAGE.md); internal, synthetic, pre-release.", ""]
        if items:
            md += ["| design item | title | status | role | feature ids |", "| --- | --- | --- | --- | --- |"]
            md += [f"| {i['design_id']} | {cell(i['title'])} | {i['status']} | {i['role']} | " + ", ".join(f"`{f}`" for f in i["feature_ids"]) + " |" for i in items]
        else:
            md += ["No design item cites a feature id of this producer."]
        files[pid + "/output.md"] = ("\n".join(md) + "\n").encode("utf-8")


def generate(core_root: Path, ref: str) -> dict[str, bytes]:
    """Return {relative path: bytes} of the whole catalogue (deterministic)."""
    files: dict[str, bytes] = {}
    contracts_index: list[dict[str, Any]] = []
    producers_index: list[dict[str, Any]] = []
    by_feature: dict[str, str] = {}
    problems: list[str] = []
    for contract_key, spec in CONTRACTS.items():
        for rel in (spec["api"], spec["checkpoint"], "packages/duckdb/src/equity_feature_duckdb/" + spec["module"] + ".py"):
            if not (ROOT / rel).is_file():
                problems.append(f"{contract_key}: io file missing: {rel}")
        raw, commit = read_core(core_root, ref, spec["path"])
        sha = hashlib.sha256(raw).hexdigest()
        contract = json.loads(raw.decode("utf-8"))
        map_excluded: dict[str, str] = {}
        if "map" in spec:
            contract, map_excluded = MAPS[spec["map"]](contract)
        if "grain" in raw.decode("utf-8").lower() and "grain" not in contract:
            problems.append(f"{contract_key}: the word 'grain' now occurs in core text; extend the extractor (grain line says it does not occur)")
        related = []
        for rel in spec["amendments"]:
            data, c = read_core(core_root, ref, rel)
            related.append({"core_path": rel, "core_commit": c, "sha256_lf": hashlib.sha256(data).hexdigest()})
        status = freeze_status(contract)
        excluded, unparsed = classify_keys(contract, map_excluded)
        prov = provenance(contract_key, spec, contract, sha, commit, related)
        unparsed_producers: dict[str, list[str]] = {}
        for name, entry in contract["producers"].items():
            iv, ov, unknown = build_producer(contract_key, spec, contract, name, entry, status, prov)
            pid = iv["producer_id"]
            if unknown:
                unparsed_producers[pid] = unknown
            files[f"{pid}/input.json"], files[f"{pid}/input.md"] = dumps(iv), input_md(iv)
            files[f"{pid}/output.json"], files[f"{pid}/output.md"] = dumps(ov), output_md(ov)
            for fid in ov["feature_ids"]:
                if fid in by_feature:
                    problems.append(f"feature id {fid} in {by_feature[fid]} and {pid}")
                by_feature[fid] = pid
            producers_index.append({
                "producer_id": pid, "family": spec["family"], "contract_key": contract_key, "contract_version": iv["contract_version"], "status": status,
                "adapter": iv["adapter"], "feature_ids": ov["feature_ids"],
                "paths": {"input_json": f"{pid}/input.json", "input_md": f"{pid}/input.md", "output_json": f"{pid}/output.json", "output_md": f"{pid}/output.md"},
            })
        contracts_index.append({"contract_key": contract_key, "family": spec["family"], "status": status, "source": prov,
                                "excluded_core_keys": excluded, "unparsed_top_level_keys": unparsed, "unparsed_producer_keys": unparsed_producers})
    deferred = []
    for rel, note in DEFERRED_EF1.items():
        data, c = read_core(core_root, ref, rel)
        status_text = str(json.loads(data.decode("utf-8")).get("status", ""))
        deferred.append({"core_path": rel, "core_commit": c, "sha256_lf": hashlib.sha256(data).hexdigest(), "core_status_text": status_text[:200], "reason": note})
    if problems:
        raise SystemExit("\n".join(problems))
    producers_index.sort(key=lambda p: p["producer_id"])
    families = sorted({p["family"] for p in producers_index})
    index = {"schema": SCHEMA, "generated": GENERATED, "wording": WORDING, "authority": AUTHORITY, "catalogue_version": IO_CONTRACTS,
             "families_present": families, "contracts": contracts_index, "not_catalogued_core_files": deferred, "producers": producers_index, "by_feature_id": dict(sorted(by_feature.items()))}
    attach_design_items(files, core_root, ref)
    files["index.json"] = dumps(index)
    files["INDEX.md"] = index_md(index)
    return dict(sorted(files.items()))


def write_tree(target: Path, files: dict[str, bytes]) -> None:
    if target.exists():
        for old in sorted(target.rglob("*"), reverse=True):
            if old.is_file():
                old.unlink()
            elif not any(old.iterdir()):
                old.rmdir()
    for rel, data in files.items():
        out = target / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(data)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--core-root", type=Path, required=True)
    parser.add_argument("--core-ref", default="origin/main")
    args = parser.parse_args()
    files = generate(args.core_root, args.core_ref)
    write_tree(DOCS_DIR, files)
    write_tree(PACKAGE_DIR, files)
    print(f"wrote {len(files)} files to {DOCS_DIR.relative_to(ROOT)} and {PACKAGE_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
