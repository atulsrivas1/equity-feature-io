def git(core_root: Path, *args: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(core_root), *args])


def read_core(core_root: Path, ref: str, path: str) -> tuple[bytes, str]:
    """LF bytes of ``path`` at ``ref`` and the last core commit that touched it as of ``ref``."""
    raw = git(core_root, "show", f"{ref}:{path}").replace(b"\r\n", b"\n")
    commit = git(core_root, "log", "-1", "--format=%H", ref, "--", path).decode("ascii").strip()
    if not commit:
        raise SystemExit(f"no core commit found for {path} at {ref}")
    return raw, commit


def freeze_status(contract: dict[str, Any]) -> str:
    """``frozen`` or ``proposed``, read from the leading words of the core ``coordinator_freeze`` text only ('Frozen as', optionally after 'Per the coordinator,', or 'Proposed freeze')."""
    text = str(contract.get("coordinator_freeze", "")).strip().lower()
    if re.match(r"(per the coordinator, )?frozen as", text):
        return "frozen"
    if text.startswith("proposed freeze"):
        return "proposed"
    raise SystemExit("coordinator_freeze text starts with a recognised freeze statement: " + text[:80])


def classify_keys(contract: dict[str, Any], extra: dict[str, str] | None = None) -> tuple[dict[str, list[str]], list[str]]:
    excluded: dict[str, list[str]] = {}
    unparsed: list[str] = []
    parsed = META_KEYS | INPUT_ROLE_KEYS | set(INPUT_RULE_KEYS) | set(OUTPUT_KEYS) | OUTPUT_OTHER_KEYS
    for key in contract:
        if key in parsed:
            continue
        reason = "test evidence" if FIXTURE_KEY.fullmatch(key) else (extra or {}).get(key, EXCLUDED.get(key))
        if reason is None:
            unparsed.append(key)
        else:
            excluded.setdefault(reason, []).append(key)
    return {r: sorted(k) for r, k in sorted(excluded.items())}, sorted(unparsed)


def role_names(contract: dict[str, Any], producer: str, entry: dict[str, Any]) -> list[str]:
    names = entry.get("roles_in_slot_order", entry.get("roles"))
    if isinstance(names, list):
        return [str(n) for n in names]
    return [str(r["role"]) for r in role_defs(contract, producer)]


def role_defs(contract: dict[str, Any], producer: str) -> list[dict[str, Any]]:
    roles = contract.get("roles")
    if not isinstance(roles, dict):
        return []
    found = roles.get(producer, roles.get("all", []))
    return [r for r in found if isinstance(r, dict)]


def parameters(entry: dict[str, Any]) -> list[dict[str, Any]]:
    raw = entry.get("parameters", [])
    if isinstance(raw, dict):
        return [{"name": k, "text": v} for k, v in raw.items()]
    return [{"name": None, "text": s} for s in raw]


def refusal_codes(contract: dict[str, Any], producer: str) -> list[dict[str, Any]]:
    """Distinct (error_code, raised_by) pairs of the core refusal fixtures, with their fixture ids; nothing is added."""
    items = contract.get("refusal_fixtures")
    if items is None and isinstance(contract.get("fixtures"), dict):
        items = contract["fixtures"].get("refusals")
    groups: dict[tuple[str, str | None], dict[str, Any]] = {}
    for item in items or []:
        if "producer" in item and item["producer"] != producer:
            continue
        key = (str(item["error_code"]), item.get("raised_by"))
        g = groups.setdefault(key, {"error_code": key[0], "raised_by": key[1], "fixture_ids": [], "example": item.get("description")})
        g["fixture_ids"].append(item["id"])
    return sorted(groups.values(), key=lambda g: (g["error_code"], str(g["raised_by"])))


