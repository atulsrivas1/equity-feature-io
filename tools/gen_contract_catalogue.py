def build_producer(contract_key: str, spec: dict[str, Any], contract: dict[str, Any], name: str, entry: dict[str, Any], status: str,
                   prov: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any], list[str]]:
    producer_id = str(entry["config_identity"])
    unknown = sorted(k for k in entry if k not in PRODUCER_KEYS and k not in PRODUCER_EXCLUDED)
    head = {
        "schema": SCHEMA, "generated": GENERATED, "wording": WORDING, "authority": AUTHORITY,
        "producer_id": producer_id, "core_producer_key": name, "family": spec["family"], "contract_version": entry["policy_version"],
        "algorithm_version": entry["algorithm_version"], "schema_version": entry["schema_version"], "status": status,
        "source_status": contract["status"], "source": prov,
    }
    adapter = {"io_module": "equity_feature_duckdb." + spec.get("producer_modules", {}).get(name, spec["module"]), "api_page": spec["api"], "api_link": IO_BLOB + spec["api"], "checkpoint": spec["checkpoint"]}
    defs = role_defs(contract, name)
    by_name = {str(d["role"]): d for d in defs}
    roles = []
    for slot, role in enumerate(role_names(contract, name, entry)):
        d = by_name.get(role, {})
        roles.append({"slot": slot, "role": role, "kind": d.get("kind"), "nullable": d.get("nullable"), "contract": d.get("contract")})
    rules = {k: contract[k] for k in INPUT_RULE_KEYS if k in contract}
    input_view = {
        **head, "view": "input", "adapter": adapter, "roles": roles, "reference_fact_schemas": contract.get("reference_fact_schemas"),
        "config_parameters": parameters(entry), "rules": rules, "unparsed_producer_keys": unknown,
        "grain": entry.get("grain", contract.get("grain")), "refusal_codes": refusal_codes(contract, name),
    }
    mine = [h for h in contract["headers"] if h.get("producer") == name]
    headers = []
    for h in mine:
        if not all(isinstance(h.get(k), str) for k in ("id", "dtype", "unit")):
            raise SystemExit(f"{contract_key}: header without string id/dtype/unit: {h.get('id')}")
        headers.append({
            "feature_id": h["id"], "dtype": h["dtype"], "unit": h["unit"], "scale": h.get("scale"), "available_when": h.get("available_when"),
            "other_core_fields": {k: v for k, v in h.items() if k not in ("id", "dtype", "unit", "scale", "available_when", "producer")},
            "feature_header_value": {"feature_id": h["id"], "algorithm_version": entry["algorithm_version"], "dtype": h["dtype"], "unit": h["unit"],
                                    "schema_version": entry["schema_version"]},
        })
    ids = {h["feature_id"] for h in headers}
    extras: dict[str, Any] = {k: contract[k] for k in OUTPUT_KEYS if k in contract and k != "unit_additions"}
    if "unit_additions" in contract:
        extras["unit_additions"] = [u for u in contract["unit_additions"] if set(u.get("used_by", [])) & ids]
    output_view = {**head, "view": "output", "headers": headers, "feature_ids": sorted(ids), **extras}
    return input_view, output_view, unknown


def dumps(obj: Any) -> bytes:
    return (json.dumps(obj, indent=2, ensure_ascii=True) + "\n").encode("ascii")


def cell(value: Any) -> str:
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=True)
    return text.replace("|", "\\|").replace("\n", " ")


def render_value(value: Any, depth: int = 0) -> list[str]:
    pad = "  " * depth
    if isinstance(value, dict):
        out: list[str] = []
        for k, v in value.items():
            if isinstance(v, (dict, list)):
                out.append(f"{pad}- **{k}**:")
                out.extend(render_value(v, depth + 1))
            else:
                out.append(f"{pad}- **{k}**: {v}")
        return out
    if isinstance(value, list):
        out = []
        for v in value:
            if isinstance(v, (dict, list)):
                out.append(f"{pad}-")
                out.extend(render_value(v, depth + 1))
            else:
                out.append(f"{pad}- {v}")
        return out
    return [f"{pad}- {value}"]


